"""Render every prompt the audit can send, byte-exact, into one reviewable file.

    python3 -m honeybee_qc.dump_prompts --out honeybee_qc/PROMPTS.md

Generated rather than hand-written on purpose: a prompt review is only worth
anything if what you read is what actually goes over the wire. Everything below
comes from calling the real builders on real data, so it cannot drift from the
code.

The rubric-stage prompts are rendered against the planted demo rubric. The
rating-stage prompts are rendered against the real 16-exchange Gemini
conversation if its snapshot is on disk, and against a small synthetic
conversation otherwise.
"""

